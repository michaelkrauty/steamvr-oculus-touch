"""Generate fictional camera fixtures with opencv-python-headless 4.12 or 5.1.

Run once per version, redirecting stdout to support/camera_<version>.inc.
Requires numpy and cv2 only for generation, never for running the C tests.
"""
import cv2
import numpy as np
import subprocess
import sys

native = sys.argv[1] if len(sys.argv) == 2 else None
version = subprocess.check_output([native], text=True).strip() if native else cv2.__version__
if not version.startswith(("4.12.", "5.1.")):
    raise SystemExit("Use OpenCV 4.12 or 5.1")


def values(a):
    return ", ".join(float(x).hex() for x in np.asarray(a).flat)


print("/* SPDX-License-Identifier: Apache-2.0")
print(f" * Synthetic fixtures generated by generate_camera_reference.py; OpenCV {version}. */")
print("static const struct camera_case camera_cases[] = {")
K = np.array([[613.0, 0, 641.0], [0, 587.0, 479.0], [0, 0, 1]])
pixels = np.array([(x, y) for y in (-400, 0, 479, 960, 1400)
                   for x in (-500, 0, 641, 1280, 1800)] + [(641.000001, 479)], np.float32)
objects = np.array([(x, y, z) for z in (0, -.5, .05, 1, 3)
                    for x, y in ((0, 0), (.03, -.02), (.1, .2), (-.6, .5))], np.float32)
# Identity, a half turn, and a generic unit rotation. Float boundaries match callers.
for fish in (0, 1):
    for coeff in ((-.08, .012, .001, -.0005, .0002), (-1, 0, 0, 0, .02)):
        d = np.array(coeff[:4] if fish else coeff, np.float64)
        fn = cv2.fisheye.undistortPoints if fish else cv2.undistortPoints
        if native:
            data = " ".join(str(float(x)) for x in np.r_[d, pixels.ravel()])
            rays = np.array(subprocess.check_output([native, "u", str(fish)], input=data,
                                                   text=True).split(), float).reshape(-1, 2)
        else:
            rays = fn(pixels.reshape(-1, 1, 2), K, d).reshape(-1, 2)
        for pixel, ray in zip(pixels, rays):
            print("{ %d, {%s}, {%s}, {%s} }," %
                  (fish, values(coeff), values(pixel), values(ray)))
print("};")
# A zero-principal-point camera whose focal length maps the float32 1e-8
# pixel to exactly 1e-8 in double precision; the other rays straddle it.
print("static const struct camera_case tiny_camera_cases[] = {")
tiny = np.array([(x, 0) for x in (0.5e-8, 1e-8, 2e-8)], np.float32)
K0 = K.copy()
K0[0, 0] = K0[1, 1] = float(np.float32(1e-8)) / 1e-8
K0[0, 2] = K0[1, 2] = 0
d = np.zeros(4, np.float64)
if native:
    data = " ".join(str(float(x)) for x in np.r_[d, tiny.ravel()])
    rays = np.array(subprocess.check_output([native, "u", "1", "zero"], input=data,
                                           text=True).split(), float).reshape(-1, 2)
else:
    rays = cv2.fisheye.undistortPoints(tiny.reshape(-1, 1, 2), K0, d).reshape(-1, 2)
for pixel, ray in zip(tiny, rays):
    print("{ 1, {0, 0, 0, 0, 0}, {%s}, {%s} }," % (values(pixel), values(ray)))
print("};")
print("static const struct projection_case projection_cases[] = {")
for fish in (0, 1):
    d = np.array([-.08, .012, .001, -.0005, .0002], np.float64)
    for q in ((0, 0, 0, 1), (0, 1, 0, 0), (.2, -.3, .1, .9)):
        q = np.array(q, np.float32)
        n = q.astype(np.float64) / np.linalg.norm(q.astype(np.float64))
        angle = 2 * np.arctan2(np.linalg.norm(n[:3]), n[3])
        r = n[:3] * (angle / np.linalg.norm(n[:3])) if angle else np.zeros(3)
        t = np.array([0, 0, 0] if angle == 0 else [.02, -.01, .125], np.float32)
        fn = cv2.fisheye.projectPoints if fish else cv2.projectPoints
        args = (objects.reshape(-1, 1, 3), r, t.astype(np.float64), K, d[:4] if fish else d)
        if native:
            data = " ".join(str(float(x)) for x in np.r_[d[:4] if fish else d, r, t, objects.ravel()])
            projected = np.array(subprocess.check_output([native, "p", str(fish)], input=data,
                                                        text=True).split(), float).reshape(-1, 2)
        else:
            projected = fn(*args)[0].reshape(-1, 2)
        for obj, pixel in zip(objects, projected):
            print("{ %d, {%s}, {%s}, {%s}, {%s} }," %
                  (fish, values(q), values(t), values(obj), values(pixel)))
print("};")
